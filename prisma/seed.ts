async function main() {
  console.log("🌱 Seeding GTA community reports...");

  await prisma.report.deleteMany();

  for (const report of communityReports) {
    await prisma.report.create({ data: report });
  }

  const count = await prisma.report.count();
  console.log(`✅ Seeded ${count} community reports across the GTA`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
